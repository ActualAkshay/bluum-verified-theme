const checksum = (content) => createHash("sha256").update(content).digest("hex")

export function snapshotContent(name, content) {
  return `/* @generated by bluum-verified-theme/scripts/sync-storefront.mjs\n * Source: ${sourceRepository}/src/runtime/${name}\n * Source SHA-256: ${checksum(content)}\n * Edit the standalone theme source, then run sync:storefront.\n * This build snapshot does not select or publish a storefront theme.\n */\n${content}`
}

// Reject symlink files and directories, including links which happen to point
// back into this checkout. Parent directories must already exist; only the
// explicitly marked new integration files can be created.
async function checkedFile(root, relative, allowMissingFinal = false) {
  const segments = relative.split("/")
  let current = root
  for (const [index, segment] of segments.entries()) {
    current = path.join(current, segment)
    let info
    try {
      info = await lstat(current)
    } catch (error) {
      if (error.code === "ENOENT" && allowMissingFinal && index === segments.length - 1) return current
      throw error
    }
    if (info.isSymbolicLink()) throw new Error(`Refusing symbolic link: ${relative}`)
    if (index < segments.length - 1 ? !info.isDirectory() : !info.isFile()) {
      throw new Error(`Expected ${index < segments.length - 1 ? "directory" : "file"}: ${relative}`)
    }
  }
  const resolved = await realpath(current)
  if (!resolved.startsWith(`${root}${path.sep}`)) throw new Error(`Target escapes storefront: ${relative}`)
  return resolved
}

function assertOwnedSnapshot(file, existing) {
  if (existing === undefined && file.allowCreation) return
  if (checksum(existing) === file.initialHash) return
  const headerEnd = existing.indexOf(" */\n")
  if (headerEnd !== -1) {
    const body = existing.slice(headerEnd + 4)
    if (existing === snapshotContent(file.name, body)) return
  }
  throw new Error(`Refusing to overwrite modified or unrecognized snapshot: ${file.target}. Move intended edits into src/runtime/${file.name} first.`)
}

async function readExisting(filePath, allowMissing) {
  try { return await readFile(filePath, "utf8") }
  catch (error) {
    if (error.code === "ENOENT" && allowMissing) return undefined
    throw error
  }
}

export async function syncStorefront({ storefront, check = false }) {
  if (!storefront) throw new Error("--storefront must point to an existing Medusa apps/storefront directory")
  const root = await realpath(path.resolve(storefront))
  const packagePath = await checkedFile(root, "package.json")
  const packageJson = JSON.parse(await readFile(packagePath, "utf8"))
  if (packageJson.name !== "storefront") throw new Error("Target package must be named storefront")

  // Validate every source and destination before the first write. Theme
  // manifests, activation state, app routes, and backend are never targets.
  const changes = []
  for (const file of runtimeFiles) {
    const sourcePath = await checkedFile(await realpath(repositoryRoot), `src/runtime/${file.name}`)
    const targetPath = await checkedFile(root, file.target, file.allowCreation)
    const source = await readFile(sourcePath, "utf8")
    const existing = await readExisting(targetPath, file.allowCreation)
    const generated = snapshotContent(file.name, source)
    if (generated !== existing) {
      if (!check) assertOwnedSnapshot(file, existing)
      changes.push({ targetPath, relative: file.target, generated, existing, allowCreation: file.allowCreation })
    }
  }

  if (!check) {
    for (const change of changes) {
      // Check again before replacing so edits made since preflight are not lost.
      await checkedFile(root, change.relative, change.allowCreation)
      if (await readExisting(change.targetPath, change.allowCreation) !== change.existing) {
        throw new Error(`Target changed during sync: ${change.relative}`)
      }
      const temporary = `${change.targetPath}.theme-sync-${randomUUID()}`
      try {
        await writeFile(temporary, change.generated, { flag: "wx" })
        await rename(temporary, change.targetPath)
      } finally {
        await unlink(temporary).catch((error) => { if (error.code !== "ENOENT") throw error })
      }
    }
  }
  return { changed: changes.map((change) => change.relative), check }
}

export function parseArguments(args) {
  let storefront
  let check = false
  for (let index = 0; index < args.length; index += 1) {
    if (args[index] === "--check" && !check) check = true
    else if (args[index] === "--storefront" && !storefront && args[index + 1] && !args[index + 1].startsWith("--")) storefront = args[++index]
    else throw new Error(`Unsupported or duplicate argument: ${args[index]}`)
  }
  if (!storefront) throw new Error("Usage: node scripts/sync-storefront.mjs --storefront /path/to/medusa/apps/storefront [--check]")
  return { storefront, check }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = await syncStorefront(parseArguments(process.argv.slice(2)))
    if (result.check && result.changed.length) {
      console.error(`Theme snapshot drift:\n${result.changed.join("\n")}`)
      process.exitCode = 1
    } else {
      console.log(result.check ? `All ${runtimeFiles.length} theme snapshots match standalone sources.` : `Synced ${result.changed.length} theme snapshot(s). Activation unchanged.`)
    }
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
